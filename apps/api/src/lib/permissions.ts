export type PermissionKey =
  (typeof PERMISSION_KEYS)[keyof typeof PERMISSION_KEYS];

/* --- LEGACY KEY NORMALIZATION --- */
/** Maps legacy camelCase keys to dot-notation permissions. */
export const LEGACY_PERMISSION_MAP: Record<string, PermissionKey> = {
  approveRequests: PERMISSION_KEYS.REQUEST_APPROVE,
  manageVendors: PERMISSION_KEYS.VENDOR_MANAGE,
  manageContracts: PERMISSION_KEYS.CONTRACT_MANAGE,
  viewControlTower: PERMISSION_KEYS.CONTROL_VIEW,
  manageCatalog: PERMISSION_KEYS.CATALOG_MANAGE,
  inviteVendors: PERMISSION_KEYS.VENDOR_INVITE,
};

export function normalizePermissionKey(
  permission: string
): string {
  return (
    LEGACY_PERMISSION_MAP[permission] ?? permission
  );
}

